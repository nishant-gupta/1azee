async function thumbnail(src, isFullPage) {
  fs.mkdirSync(THUMBS, { recursive: true });
  const name = `${crypto.createHash('sha1').update(path.relative(ROOT, src)).digest('hex').slice(0, 12)}.jpg`;
  const out = path.join(THUMBS, name);
  if (!fs.existsSync(out)) {
    // eslint-disable-next-line global-require, import/no-dynamic-require
    const sharp = require(SHARP);
    const width = isFullPage ? 640 : 1000;
    const maxH = isFullPage ? 1400 : 700;
    const resized = await sharp(src).resize({ width, withoutEnlargement: true }).toBuffer();
    const meta = await sharp(resized).metadata();
    await sharp(resized)
      .extract({
        left: 0, top: 0, width: meta.width, height: Math.min(meta.height, maxH),
      })
      .jpeg({ quality: 78 }).toFile(out);
  }
  return { file: out, daName: `site-analysis/${name}` };
}

async function toDaHtml(md) {
  // eslint-disable-next-line global-require, import/no-dynamic-require
  const { marked } = require(MARKED);
  marked.setOptions({ mangle: false, headerIds: false });
  const tokens = marked.lexer(md.replace(/<!-- APPENDIX:(START|END)[^>]*-->/g, ''));
  const row = (cells) => `<div>${cells.map((c) => `<div>${marked.parseInline(c.text)}</div>`).join('')}</div>`;
  const sections = [[]];
  tokens.forEach((tok) => {
    if (tok.type === 'hr') { sections.push([]); return; }
    if (tok.type === 'space' || tok.type === 'html') return;
    sections[sections.length - 1].push(tok.type === 'table'
      ? `<div class="table">${row(tok.header)}${tok.rows.map(row).join('')}</div>`
      : marked.parser(Object.assign([tok], { links: tokens.links })));
  });
  let html = sections.filter((s) => s.length).map((s) => `<div>${s.join('\n')}</div>`).join('\n');

  // Upload screenshots (as thumbnails) and point the images at DA.
  const srcs = [...new Set([...html.matchAll(/<img\b[^>]*\ssrc="([^"]+)"/g)].map((m) => m[1]))];
  const map = {};
  // Sequential on purpose: one thumbnail + upload at a time.
  await srcs.reduce((chain, src) => chain.then(async () => {
    const file = path.resolve(path.dirname(MD), src);
    if (!fs.existsSync(file)) throw new Error(`screenshot not found: ${src}`);
    const t = await thumbnail(file, file.endsWith('full-page.jpg'));
    map[src] = uploadImage(t.file, t.daName);
  }), Promise.resolve());
  html = html.replace(/(<img\b[^>]*\ssrc=")([^"]+)(")/g, (m, a, src, b) => `${a}${map[src] || src}${b}`);

  const meta = '<div><div class="metadata"><div><div>Title</div><div>myastrazeneca.ch: Site Analysis and Migration Report</div></div><div><div>Robots</div><div>noindex, nofollow</div></div></div></div>';
  return { html: `${html}\n${meta}`, images: srcs.length };
}

(async () => {
  const data = loadData();
  writeMarkdown(buildAppendix(data));
  console.log(`Appendices written to ${path.relative(ROOT, MD)} (${data.templates.length} templates, ${Object.keys(data.variants).length} variants, ${data.failedUrls.length} excluded pages).`);

  if (!process.argv.includes('--publish')) return;
  const { html, images } = await toDaHtml(fs.readFileSync(MD, 'utf8'));
  console.log(`Converted to DA HTML with ${images} screenshot(s).`);
  process.exitCode = report([publishDoc(PAGE, html, !process.argv.includes('--no-live'))]);
})().catch((e) => { console.error(e); process.exitCode = 1; });
