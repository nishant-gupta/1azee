/*
 * Builds the site-analysis report.
 *
 *   node tools/da/build-site-analysis.js            regenerate the appendices in docs/site-analysis.md
 *   node tools/da/build-site-analysis.js --publish  ...then publish it to DA as /docs/site-analysis
 *   add --no-live to preview only
 *
 * The appendices (every URL per template, template screenshots, template x block matrix,
 * and one screenshot per block variant) are generated from catalog/ and written between
 * the APPENDIX markers, so hand-written sections above them are preserved.
 * Screenshots are shrunk into migration-work/da-publish/analysis-images/ before upload.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {
  STAGE, uploadImage, publishDoc, report,
} = require('./publish-content.js');

const ROOT = process.cwd();
const MD = path.join(ROOT, 'docs', 'site-analysis.md');
const CATALOG = path.join(ROOT, 'catalog');
const THUMBS = path.join(STAGE, 'analysis-images');
const PAGE = 'docs/site-analysis';
const START = '<!-- APPENDIX:START (generated by tools/da/build-site-analysis.js; do not edit by hand) -->';
const END = '<!-- APPENDIX:END -->';
const MARKED = '/home/node/.excat-marketplaces/excat-marketplace/excat/tools/excatops-mcp/node_modules/marked';
const SHARP = '/home/node/.excat-marketplaces/excat-marketplace/edge-delivery-services/skills/scrape-webpage/scripts/node_modules/sharp';

const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const rel = (f) => path.relative(path.dirname(MD), f).split(path.sep).join('/');

/* ------------------------------------------------------------------ data */

function loadData() {
  const { templates } = readJson(path.join(CATALOG, 'template-catalog.json'));
  const variants = readJson(path.join(CATALOG, 'block-catalog.json'))['block-catalog'].blockVariants;

  const pages = {};
  const pagesDir = path.join(CATALOG, '.pages');
  fs.readdirSync(pagesDir).forEach((slug) => {
    const f = path.join(pagesDir, slug, 'page-catalog.json');
    if (!fs.existsSync(f)) return;
    const pc = readJson(f);
    pages[pc.url] = { slug, dir: path.join(pagesDir, slug), ...pc };
  });

  const templateOf = {};
  templates.forEach((t) => t.urls.forEach((u) => { templateOf[u] = t.name; }));

  // variant id -> instances [{ url, template, shot }]
  const instances = {};
  Object.values(pages).forEach((p) => (p.blocks || []).forEach((b) => {
    (instances[b.variantId] = instances[b.variantId] || []).push({
      url: p.url, template: templateOf[p.url], shot: b.screenshot ? path.join(p.dir, b.screenshot) : null,
    });
  }));

  // variant id -> EDS block(s) that declare it in blocks/*/metadata.json
  const edsBlocks = {};
  fs.readdirSync(path.join(ROOT, 'blocks')).forEach((b) => {
    const m = path.join(ROOT, 'blocks', b, 'metadata.json');
    if (!fs.existsSync(m)) return;
    (readJson(m).memberVariantIds || []).forEach((id) => { (edsBlocks[id] = edsBlocks[id] || []).push(b); });
  });

  const failed = readJson(path.join(CATALOG, 'urls-checklist.json'));
  const failedUrls = new Set();
  JSON.stringify(failed, (k, v) => {
    if (v && typeof v === 'object' && v.url && /fail|error/i.test(String(v.status))) failedUrls.add(v.url);
    return v;
  });

  return {
    templates, variants, pages, templateOf, instances, edsBlocks, failedUrls: [...failedUrls].sort(),
  };
}

const locale = (u) => (new URL(u).pathname.match(/^\/(de|fr|it|en)\//) || [null, '-'])[1].toUpperCase();
function section(u) {
  const p = new URL(u).pathname;
  if (p === '/' || /\/startseite\.html$/.test(p)) return 'Homepage';
  if (/see-the-pattrns/.test(p)) return 'See the pATTRns';
  if (/trixeo\/ressourcen\//.test(p)) return 'Trixeo resource doc';
  if (/produkte\/trixeo/.test(p)) return 'Trixeo product';
  if (/produkte\.html/.test(p)) return 'Products index';
  if (/contact-us/.test(p)) return 'Contact';
  if (/therapiegebiete/.test(p)) return 'Therapy area';
  return 'Other';
}
function shortPath(u) {
  const p = new URL(u).pathname.replace(/\.html$/, '');
  const rest = p.replace(/^\/(de|fr|it|en)\/startseite/, '');
  return rest ? `/…${rest}` : (p || '/'); // homepages keep their full path, e.g. /en/startseite
}
const TYPE_ORDER = ['header', 'footer', 'hero', 'cards', 'columns', 'accordion', 'tabs', 'form', 'breadcrumbs', 'unknown'];
const vType = (v) => v.name || v.type || 'unknown';

/* ------------------------------------------------------------ appendices */

function buildAppendix(d) {
  const out = [];
  const w = (s = '') => out.push(s);

  w('---');
  w();
  w('## Appendix A: Every page, by template');
  w();
  w('Each row is one analyzed page with the block variants detected on it. Look up any variant ID in Appendix D to see its screenshot and details. Use this to check whether each page really belongs in its template.');
  d.templates.forEach((t, ti) => {
    w();
    w(`### A.${ti + 1} ${t.name} (${t.urls.length} pages)`);
    w();
    w(`*${esc(t.description)}*`);
    w();
    w('| # | Locale | Section | Page title | Block variants on the page | URL |');
    w('|---:|---|---|---|---|---|');
    [...t.urls].sort().forEach((u, i) => {
      const p = d.pages[u] || {};
      const vs = [...new Set((p.blocks || []).map((b) => `${b.type} \`${b.variantId}\``))].join(', ') || '(none)';
      w(`| ${i + 1} | ${locale(u)} | ${section(u)} | ${esc(p.title)} | ${esc(vs)} | [${esc(shortPath(u))}](${u}) |`);
    });
  });
  w();
  w(`### A.${d.templates.length + 1} Excluded pages (failed analysis)`);
  w();
  w('| # | Locale | URL | Reason |');
  w('|---:|---|---|---|');
  d.failedUrls.forEach((u, i) => w(`| ${i + 1} | ${locale(u)} | [${esc(shortPath(u))}](${u}) | HTTP 404 on the source site |`));

  w();
  w('---');
  w();
  w('## Appendix B: Template reference screenshots');
  w();
  w('Top of each template\'s first page (full-page captures are cropped to the upper part of the page).');
  d.templates.forEach((t, ti) => {
    const u = t.urls[0];
    const p = d.pages[u];
    w();
    w(`### B.${ti + 1} ${t.name}`);
    w();
    w(`Page: [${esc(shortPath(u))}](${u})`);
    const shot = p && path.join(p.dir, 'full-page.jpg');
    if (shot && fs.existsSync(shot)) { w(); w(`![${t.name}: ${esc(p.title)}](${rel(shot)})`); }
  });

  w();
  w('---');
  w();
  w('## Appendix C: Template × block type matrix');
  w();
  w('Number of pages in each template that contain at least one block of that type. "unknown" means content the detector could not map to a named block (mostly default content).');
  w();
  const types = TYPE_ORDER.filter((ty) => !['header', 'footer'].includes(ty));
  w(`| Template | Pages | ${types.join(' | ')} |`);
  w(`|---|---:|${types.map(() => '---:').join('|')}|`);
  d.templates.forEach((t) => {
    const counts = types.map((ty) => t.urls.filter((u) => (d.pages[u]?.blocks || []).some((b) => b.type === ty)).length);
    w(`| ${t.name} | ${t.urls.length} | ${counts.map((c) => c || '·').join(' | ')} |`);
  });

  w();
  w('---');
  w();
  w('## Appendix D: Block variant catalog');
  w();
  w('One entry per detected variant: its structure, how many pages use it, which templates it appears in, which EDS block implements it today (from each block\'s `metadata.json`), and an example screenshot. Variants with no EDS block are candidates for default content or a new block.');
  const vids = Object.keys(d.variants).sort((a, b) => {
    const ta = TYPE_ORDER.indexOf(vType(d.variants[a])); const tb = TYPE_ORDER.indexOf(vType(d.variants[b]));
    return (ta - tb) || ((d.instances[b] || []).length - (d.instances[a] || []).length) || a.localeCompare(b);
  });
  vids.forEach((id, i) => {
    const v = d.variants[id];
    const inst = d.instances[id] || [];
    const pageSet = [...new Set(inst.map((x) => x.url))];
    const byTpl = {};
    pageSet.forEach((u) => { const t = d.templateOf[u] || '(none)'; byTpl[t] = (byTpl[t] || 0) + 1; });
    const isGlobal = id.endsWith('-global');
    const eds = d.edsBlocks[id]?.map((b) => `\`${b}\``).join(', ') || (isGlobal ? `\`${vType(v)}\` (global)` : 'none yet');
    const examples = pageSet.sort((a, b) => (locale(a) === 'EN' ? -1 : 0) - (locale(b) === 'EN' ? -1 : 0)).slice(0, 3);

    w();
    w(`### D.${i + 1} ${vType(v)}: \`${id}\``);
    w();
    w('| Field | Value |');
    w('|---|---|');
    w(`| Detected type | ${vType(v)} |`);
    w(`| Structure | ${esc(v.description)} |`);
    w(`| Pages using it | ${isGlobal ? 'every page (global)' : pageSet.length} |`);
    w(`| Templates | ${isGlobal ? 'all' : esc(Object.entries(byTpl).sort((a, b) => b[1] - a[1]).map(([t, n]) => `${t} (${n})`).join(', ')) || '-'} |`);
    w(`| EDS block today | ${eds} |`);
    if (examples.length) w(`| Example pages | ${examples.map((u) => `[${esc(shortPath(u))}](${u})`).join('<br>')} |`);

    let shot = null;
    if (isGlobal) {
      const g = path.join(CATALOG, '.pages', '_global', `${vType(v)}.jpg`);
      if (fs.existsSync(g)) shot = g;
    } else {
      const withShot = inst.filter((x) => x.shot && fs.existsSync(x.shot));
      shot = (withShot.find((x) => locale(x.url) === 'EN') || withShot[0])?.shot || null;
    }
    if (shot) { w(); w(`![${vType(v)} ${id}](${rel(shot)})`); }
  });
  return out.join('\n');
}

function writeMarkdown(appendix) {
  let md = fs.readFileSync(MD, 'utf8');
  const block = `${START}\n\n${appendix}\n\n${END}`;
  if (md.includes(START) && md.includes(END)) {
    md = md.slice(0, md.indexOf(START)) + block + md.slice(md.indexOf(END) + END.length);
  } else {
    md = `${md.trimEnd()}\n\n${block}\n`;
  }
  fs.writeFileSync(MD, md);
}

/* --------------------------------------------------------------- publish */

async function thumbnail(src, isFullPage) {
  fs.mkdirSync(THUMBS, { recursive: true });
  const name = `${crypto.createHash('sha1').update(path.relative(ROOT, src)).digest('hex').slice(0, 12)}.jpg`;
  const out = path.join(THUMBS, name);
  if (!fs.existsSync(out)) {
    // eslint-disable-next-line global-require, import/no-dynamic-require
    const sharp = require(SHARP);
    const width = isFullPage ? 640 : 1000;
    const maxH = isFullPage ? 1400 : 700;
    const resized = await sharp(src).resize({ width, withoutEnlargement: true }).toBuffer();
    const meta = await sharp(resized).metadata();
    await sharp(resized)
      .extract({
        left: 0, top: 0, width: meta.width, height: Math.min(meta.height, maxH),
      })
      .jpeg({ quality: 78 }).toFile(out);
  }
  return { file: out, daName: `site-analysis/${name}` };
}

async function toDaHtml(md) {
  // eslint-disable-next-line global-require, import/no-dynamic-require
  const { marked } = require(MARKED);
  marked.setOptions({ mangle: false, headerIds: false });
  const tokens = marked.lexer(md.replace(/<!-- APPENDIX:(START|END)[^>]*-->/g, ''));
  const row = (cells) => `<div>${cells.map((c) => `<div>${marked.parseInline(c.text)}</div>`).join('')}</div>`;
  const sections = [[]];
  tokens.forEach((tok) => {
    if (tok.type === 'hr') { sections.push([]); return; }
    if (tok.type === 'space' || tok.type === 'html') return;
    sections[sections.length - 1].push(tok.type === 'table'
      ? `<div class="table">${row(tok.header)}${tok.rows.map(row).join('')}</div>`
      : marked.parser(Object.assign([tok], { links: tokens.links })));
  });
  let html = sections.filter((s) => s.length).map((s) => `<div>${s.join('\n')}</div>`).join('\n');

  // Upload screenshots (as thumbnails) and point the images at DA.
  const srcs = [...new Set([...html.matchAll(/<img\b[^>]*\ssrc="([^"]+)"/g)].map((m) => m[1]))];
  const map = {};
  // Sequential on purpose: one thumbnail + upload at a time.
  await srcs.reduce((chain, src) => chain.then(async () => {
    const file = path.resolve(path.dirname(MD), src);
    if (!fs.existsSync(file)) throw new Error(`screenshot not found: ${src}`);
    const t = await thumbnail(file, file.endsWith('full-page.jpg'));
    map[src] = uploadImage(t.file, t.daName);
  }), Promise.resolve());
  html = html.replace(/(<img\b[^>]*\ssrc=")([^"]+)(")/g, (m, a, src, b) => `${a}${map[src] || src}${b}`);

  const meta = '<div><div class="metadata"><div><div>Title</div><div>myastrazeneca.ch: Site Analysis and Migration Report</div></div><div><div>Robots</div><div>noindex, nofollow</div></div></div></div>';
  return { html: `${html}\n${meta}`, images: srcs.length };
}

(async () => {
  const data = loadData();
  writeMarkdown(buildAppendix(data));
  console.log(`Appendices written to ${path.relative(ROOT, MD)} (${data.templates.length} templates, ${Object.keys(data.variants).length} variants, ${data.failedUrls.length} excluded pages).`);

  if (!process.argv.includes('--publish')) return;
  const { html, images } = await toDaHtml(fs.readFileSync(MD, 'utf8'));
  console.log(`Converted to DA HTML with ${images} screenshot(s).`);
  process.exitCode = report([publishDoc(PAGE, html, !process.argv.includes('--no-live'))]);
})().catch((e) => { console.error(e); process.exitCode = 1; });
